# Renders the Persian clock glyphs (Vazirmatn) into 4-bit alpha bitmaps for clock.cpp.
# Every item in a set shares the same height so they line up on one baseline.
import sys
from PIL import Image, ImageDraw, ImageFont
FB = sys.argv[1]; OUT = sys.argv[2]
FA = '۰۱۲۳۴۵۶۷۸۹'
WEEK = ['دوشنبه', 'سه‌شنبه', 'چهارشنبه', 'پنجشنبه', 'جمعه', 'شنبه', 'یکشنبه']   # Monday first
TEXT = ['صبح بخیر', 'شب بخیر', 'زود زدی!', 'میلی‌ثانیه', 'آفرین!', 'صبر کن...', 'حالا!']
MONTH = ['فروردین', 'اردیبهشت', 'خرداد', 'تیر', 'مرداد', 'شهریور',
         'مهر', 'آبان', 'آذر', 'دی', 'بهمن', 'اسفند']

def render_set(name, items, size, pad=0):
    f = ImageFont.truetype(FB, size, layout_engine=ImageFont.Layout.RAQM)
    imgs = []
    for s in items:
        im = Image.new('L', (size * 8, size * 2), 0)
        ImageDraw.Draw(im).text((size // 2, size // 2), s, font=f, fill=255, direction='rtl', language='fa')
        imgs.append(im)
    # common vertical box across the whole set
    top = min(im.getbbox()[1] for im in imgs); bot = max(im.getbbox()[3] for im in imgs)
    out = []
    for im in imgs:
        b = im.getbbox()
        c = im.crop((b[0] - pad, top, b[2] + pad, bot))
        out.append(c)
    return out

def emit(name, imgs, lines):
    data = []; meta = []
    for im in imgs:
        w, h = im.size; px = list(im.tobytes()); off = len(data)
        row_bytes = (w + 1) // 2
        for y in range(h):
            for x in range(0, w, 2):
                a = px[y * w + x] >> 4
                b = (px[y * w + x + 1] >> 4) if x + 1 < w else 0
                data.append((a << 4) | b)
        meta.append((w, h, off))
    lines.append('static const uint8_t %s_data[%d] = {' % (name, len(data)))
    for i in range(0, len(data), 32):
        lines.append('  ' + ','.join(str(v) for v in data[i:i + 32]) + ',')
    lines.append('};')
    lines.append('static const Glyph %s[%d] = {' % (name, len(meta)))
    for w, h, off in meta:
        lines.append('  {%d, %d, %s_data + %d},' % (w, h, name, off))
    lines.append('};')
    return sum(len(i.tobytes()) for i in imgs), len(data)

L = ['// Generated by tools/make_clock_assets.py from Vazirmatn (OFL). Do not edit.',
     '// 4-bit alpha, two pixels per byte (high nibble first), rows padded to whole bytes.',
     '#pragma once', '#include <stdint.h>',
     'struct Glyph { uint16_t w, h; const uint8_t* a; };']
emit('BIG', render_set('BIG', list(FA), 132, pad=1), L)
# date line: digits, weekdays and months share one baseline box
small = render_set('DATE', list(FA) + WEEK + MONTH, 40, pad=1)
emit('SMALL', small[:10], L); emit('WEEK', small[10:17], L); emit('MONTH', small[17:], L)
emit('TEXT', render_set('TEXT', TEXT, 40, pad=1), L)   # order must match the TX_ enum in ui.h
print('date line height', small[0].size[1])
open(OUT, 'w').write('\n'.join(L) + '\n')
