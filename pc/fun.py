# names people might call it by mistake (the old name, look-alikes)
WRONG_NAMES = ["تادا", "تا دا", "لابو", "لا بو", "بابو", "لوبو", "لبی"]
NAME_REPLIES = [
    "اِ! اسم من {name}ـه، نه {wrong}! دفعه‌ی بعد درست صدام کن، وگرنه قهر می‌کنم.",
    "{wrong}؟! {wrong} کیه دیگه؟ من {name}م، همون رباتِ خوشگلِ روی میز!",
    "ای بابا، باز گفتی {wrong}! اسمم {name}ـه، یادت بمونه دیگه.",
    "من {wrong} نیستم ها! {name}م، {name}! با لام و ب و واو.",
]

_last = []


def _pick(items):
    """random, but not one of the last few"""
    pool = [i for i in range(len(items)) if i not in _last] or list(range(len(items)))
    i = random.choice(pool)
    _last.append(i)
    del _last[:-min(8, len(items) - 1)]
    return items[i]


def fun_answer(text, name="لبو"):
    """(reply, emotion) or None"""
    t = text.strip()
    for w in WRONG_NAMES:
        if w in t and name not in t:
            return random.choice(NAME_REPLIES).format(name=name, wrong=w.replace(" ", "")), "angry"
    if JOKE_WORDS.search(t):
        return _pick(JOKES), "happy"
    return None
